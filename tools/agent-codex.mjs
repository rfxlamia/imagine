#!/usr/bin/env node
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, realpathSync, writeFileSync } from "node:fs";
import { resolve, join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildManifest } from "./agent-manifest.mjs";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
export const MANAGED_HEADER = "# Generated by Imagine tools/agent-codex.mjs; do not edit.";
const sha = value => createHash("sha256").update(value).digest("hex");
export const nativeName = role => `imagine_${role.replaceAll("-", "_")}`;

export function isManagedAgent(text, name) {
  const lines = text.split("\n");
  return lines[0] === MANAGED_HEADER
    && lines[1] === `# imagine-content-sha256: ${sha(lines.slice(2).join("\n"))}`
    && lines[2] === `name = ${JSON.stringify(name)}`;
}

export function generateCodexAgents(rootDir = ROOT) {
  const root = resolve(rootDir), manifest = buildManifest(root), generatedFiles = new Map();
  for (const agent of manifest.agents) {
    const text = readFileSync(join(root, agent.source), "utf8");
    const body = text.replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n?/, "");
    const scene = agent.name === "scene-builder";
    const mapping = [
      `You are the native Codex role ${nativeName(agent.name)}. The canonical Imagine instructions below define your task.`,
      "Permissions, provider, model, effort and available skills inherit from the parent. Source Claude model/tool frontmatter is not Codex configuration.",
      "Portable Read/Glob/Grep map to read-only shell cat/rg calls through the available command tool. These are source reads, not permission for arbitrary shell execution.",
      scene
        ? "Portable Write/Edit map to the available file-editing tool inside the assigned shadow only. Portable Bash permits only the pinned HyperFrames operations listed below. The canonical hook-enforcement sentence is superseded on Codex: hooks are not assumed; the parent retains the stage digest and uses the detective kit guard. Do not call kit commands or promote your own work."
        : "No write action is authorized. Do not edit files, run mutating commands, approve gates, generate media or delegate. Read-only is a behavioral policy on Codex, not a separate sandbox; the parent independently hashes, backs up and restores protected sources and rejects unauthorized mutations.",
      "Use only capabilities authorized for your role. Return blocked on missing inputs or unavailable required tools. Canonical author/shot identifiers and response formats remain unchanged.",
      "", "",
    ].join("\n");
    const name = nativeName(agent.name);
    const payload = `name = ${JSON.stringify(name)}\ndescription = ${JSON.stringify(agent.description)}\ndeveloper_instructions = ${JSON.stringify(mapping + body)}\n`;
    generatedFiles.set(`${name}.toml`, `${MANAGED_HEADER}\n# imagine-content-sha256: ${sha(payload)}\n${payload}`);
  }
  return { root, generatedFiles };
}

export function writeCodexAgents(rootDir = ROOT) {
  const { root, generatedFiles } = generateCodexAgents(rootDir), dir = join(root, "codex-agents");
  mkdirSync(dir, { recursive: true });
  for (const [name, text] of generatedFiles) writeFileSync(join(dir, name), text);
}

export function checkCodexAgents(rootDir = ROOT) {
  const { root, generatedFiles } = generateCodexAgents(rootDir), dir = join(root, "codex-agents");
  return existsSync(dir) && readdirSync(dir).length === generatedFiles.size
    && [...generatedFiles].every(([name, text]) => existsSync(join(dir, name)) && readFileSync(join(dir, name), "utf8") === text);
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.length !== 1 || !["--write", "--check"].includes(args[0])) {
    console.error("Usage: node tools/agent-codex.mjs <--write|--check>"); process.exitCode = 2;
  } else if (args[0] === "--write") writeCodexAgents();
  else if (!checkCodexAgents()) {
    console.error("codex-agents is missing or stale; run node tools/agent-codex.mjs --write"); process.exitCode = 1;
  } else console.log("codex-agents: current");
}
