import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, cpSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { generateCodexAgents, writeCodexAgents, checkCodexAgents } from "./agent-codex.mjs";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
function fixture(t) {
  const root = mkdtempSync(join(tmpdir(), "imagine-codex-generator-"));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  cpSync(join(ROOT, "agents"), join(root, "agents"), { recursive: true });
  return root;
}
const instructions = text => JSON.parse(text.split("\n").find(line => line.startsWith("developer_instructions = ")).slice("developer_instructions = ".length));

test("five native roles are generated from canonical bodies without pinning permissions or models", () => {
  const { generatedFiles } = generateCodexAgents(ROOT);
  assert.equal(generatedFiles.size, 5);
  for (const [name, text] of generatedFiles) {
    assert.match(name, /^imagine_[a-z_]+\.toml$/);
    assert.match(text, /^# Generated by Imagine/);
    assert.match(text, /\nname = "imagine_/); assert.match(text, /\ndescription = "/);
    assert.doesNotMatch(text, /\n(?:model|model_provider|sandbox_mode|approval_policy)\s*=/);
    const sourceName = name.replace(/^imagine_/, "").replace(/\.toml$/, "").replaceAll("_", "-");
    const body = readFileSync(join(ROOT, "agents", `${sourceName}.md`), "utf8").replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n?/, "");
    assert.ok(instructions(text).endsWith(body), `${name} must retain the canonical body`);
    assert.match(instructions(text), /inherit.*parent/i);
    assert.match(instructions(text), /read.only shell/i);
    if (sourceName === "scene-builder") assert.match(instructions(text), /hook.*kit guard/is);
  }
});

test("generation preserves multiline strings, quotes, backslashes and Unicode", t => {
  const root = fixture(t), path = join(root, "agents/storyboard-artist.md");
  const suffix = '\nUnicode café 日本語; quote "double"; path C:\\fixture\\shot; triple """.\n';
  writeFileSync(path, readFileSync(path, "utf8") + suffix);
  const text = generateCodexAgents(root).generatedFiles.get("imagine_storyboard_artist.toml");
  assert.ok(instructions(text).endsWith(suffix));
});

test("drift check rejects missing, edited and extra generated artifacts", t => {
  const root = fixture(t);
  assert.equal(checkCodexAgents(root), false);
  writeCodexAgents(root); assert.equal(checkCodexAgents(root), true);
  const path = join(root, "codex-agents/imagine_storyboard_artist.toml");
  writeFileSync(path, readFileSync(path, "utf8") + "# local edit\n");
  assert.equal(checkCodexAgents(root), false);
  writeCodexAgents(root); mkdirSync(join(root, "codex-agents"), { recursive: true });
  writeFileSync(join(root, "codex-agents/stale.toml"), "name='stale'\n");
  assert.equal(checkCodexAgents(root), false);
});

test("committed Codex artifacts match their canonical source", () => {
  assert.equal(checkCodexAgents(ROOT), true);
});
