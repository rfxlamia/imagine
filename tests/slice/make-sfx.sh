#!/usr/bin/env bash
# Generates the slice SFX "lamp-on": a short filtered noise click with a fast decay.
# Original sound (no third-party material), so its licence is "original".
set -euo pipefail
out="${1:?usage: make-sfx.sh <out-dir>}"
mkdir -p "$out"
ffmpeg -hide_banner -loglevel error -y \
  -f lavfi -i "anoisesrc=d=0.40:c=pink:a=0.5:s=8" \
  -af "highpass=f=400,lowpass=f=5000,afade=t=in:d=0.004,afade=t=out:st=0.02:d=0.38" \
  -ar 48000 -ac 1 -c:a pcm_s16le -map_metadata -1 -fflags +bitexact -flags:a +bitexact \
  "$out/lamp-on.wav"
cat > "$out/lamp-on.licence.yaml" <<'EOF'
license: original
source: generated by tests/slice/make-sfx.sh (ffmpeg anoisesrc, seed 8)
credit: Imagine slice (original sound)
EOF
