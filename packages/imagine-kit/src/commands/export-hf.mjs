// Rows of the existing STORYBOARD.md assets table, keyed by asset id, so a per-shot export keeps other shots' rows.
function existingRows(path) {
  const rows = new Map();
  if (!path || !existsSync(path)) return rows;
  for (const line of readFileSync(path, "utf8").split("\n")) {
    const m = line.match(/^\| ([^|\s]+) \| (?:img|vo|music|sfx) \|/);
    if (m) rows.set(m[1], line);
  }
  return rows;
}
function storyboardDoc(sctx, synced, keep = new Map()) {
  const own = new Set(synced.map((a) => a.id));
  const rows = [...[...keep].filter(([id]) => !own.has(id)).map(([, line]) => line), ...synced.map((a) => `| ${a.id} | ${a.kind} | v${a.v} | edit/assets/${exportName(a)} | ${a.q === undefined ? "" : `${a.q} ${a.tier}`} |`)];
  return ["<!-- generated by imagine-kit export-hf; edit STORY.md through patch apply, not this file -->", "",
    renderStory({ front: sctx.story.front, shots: sctx.story.shots }), "",
    "## Assets", "", "| id | kind | version | file | q |", "| --- | --- | --- | --- | --- |", ...rows, ""].join("\n");
}

// A context limited to one shot: its story shot, the assets it declares (every version of each id) and no project-wide VO units,
// so other shots' assets are neither checked nor copied.
function scopeToShot(sctx, shot) {
  const ids = new Set((parsedKeys(shot).assets ?? []).map((d) => d.id));
  return { ...sctx, story: { ...sctx.story, shots: [shot] }, manifest: { ...sctx.manifest, assets: sctx.manifest.assets.filter((a) => ids.has(a.id)) }, units: { ...sctx.units, units: {} } };
}
export default {
  locks: true,
  options: {},
  // Usage: export-hf [shot id]. With a shot id, only that shot's own dependencies are checked and exported (Requirements 8.4, 8.8).
  async run(_args, ctx) {
    if (_args.positionals.length > 1) throw new UsageError("usage: export-hf [shot id]");
    const { dir, rel } = resolveProject(ctx.cwd, _args.values.project);
    if (loadProject(dir).purges?.length) throw new KitError("HARD", "media was purged from this project; HyperFrames export is disabled", { rule: "HARD-PURGED" });
    const sctx = createContext(dir);
    const derived = deriveAll(sctx);
    // Additive (Req 13.7): appended after the existing keys.
    const extra = { checkpoints: checkpointsSummary(sctx.project), item_states: itemStates(derived.items) };
    const empty = { shots: [], assets: [], ...extra };
    const errors = [];
    const only = _args.positionals[0] ? shotOrThrow(sctx, _args.positionals[0]) : null;
    const shots = only ? [only] : sctx.story.shots;
    if (derived.gates.G4.state !== "approved") errors.push(err("HARD-GATES-RECORDED", "HARD", "G4", `gate G4 must be approved (state: ${derived.gates.G4.state})`));
    if (errors.length) return { project: rel, data: empty, errors };
    const hf = safePath(dir, "edit/hyperframes.json");
    if (!hf) throw new KitError("HARD", "edit/hyperframes.json resolves outside the project", { rule: "HARD-ASSETS-APPROVED", item: "edit/hyperframes.json" });
    if (!existsSync(hf)) {
      throw new KitError("BLOCKED", "edit/ is not an initialised HyperFrames project (edit/hyperframes.json is missing); run `npx hyperframes@0.8.223 init edit`", { rule: "HARD-ROOT-MOTION" });
    }
    // G5a/G5b are not evaluated project-wide: each exported shot must have its own asset dependencies ready (Requirements 8.5, 8.7).
    const readyErrors = shots.flatMap((s) => dependencyErrors(derived, sctx, s, shotAssetItemIds(sctx, s)));
    const scoped = only ? scopeToShot(sctx, only) : sctx;
    const check = checkAssets(dir, scoped, derived);
    const story = validateStory(inputsFrom(sctx));
    // A dependency named by the readiness check (with its state, or as stale) replaces checkAssets' generic "not approved" line for it.
    const named = new Set(readyErrors.map((e) => e.item));
    const assetErrors = check.errors.filter((e) => !(/is not approved at its gate/.test(e.message) && named.has(`asset:${e.item}`)));
    const all = [...assetErrors, ...readyErrors, ...story.errors];
    if (all.length) return { project: rel, data: empty, errors: all, advice: story.advice, not_run: story.not_run };

    const assetsDir = safePath(dir, "edit/assets");
    if (!assetsDir) throw new KitError("HARD", "edit/assets resolves outside the project", { rule: "HARD-ASSETS-APPROVED", item: "edit/assets" });
    for (const a of check.used) {
      const dest = safePath(dir, `edit/assets/${exportName(a)}`);
      const src = safePath(dir, a.path);
      if (!dest || !src) throw new KitError("HARD", `${a.id}.v${a.v} resolves outside the project`, { rule: "HARD-ASSETS-APPROVED", item: `${a.id}.v${a.v}` });
    }
    const sbPath = safePath(dir, "edit/STORYBOARD.md");
    if (!sbPath) throw new KitError("HARD", "edit/STORYBOARD.md resolves outside the project", { rule: "HARD-ASSETS-APPROVED", item: "edit/STORYBOARD.md" });

    mkdirSync(assetsDir, { recursive: true });
    for (const a of check.used) {
      const dest = safePath(dir, `edit/assets/${exportName(a)}`);
      const src = safePath(dir, a.path);
      if (!dest || !src) throw new KitError("HARD", `${a.id}.v${a.v} resolves outside the project`, { rule: "HARD-ASSETS-APPROVED", item: `${a.id}.v${a.v}` });
      if (!existsSync(dest) || sha256File(dest) !== a.sha256) placeFile(src, dest);
    }
    const finalSb = safePath(dir, "edit/STORYBOARD.md");
    if (!finalSb) throw new KitError("HARD", "edit/STORYBOARD.md resolves outside the project", { rule: "HARD-ASSETS-APPROVED", item: "edit/STORYBOARD.md" });
    writeAtomic(finalSb, storyboardDoc(sctx, check.used, only ? existingRows(finalSb) : new Map()));
    const journal_id = appendJournal(dir, { command: "export-hf", summary: `${shots.length} shots, ${check.used.length} assets`, now: ctx.now() });
    return { project: rel, journal_id, advice: story.advice, not_run: story.not_run,
      data: { shots: shots.map((s) => s.id), assets: check.used.map((a) => ({ id: a.id, v: a.v, kind: a.kind, path: `edit/assets/${exportName(a)}`, sha256: a.sha256 })), ...extra } };
  },
};
