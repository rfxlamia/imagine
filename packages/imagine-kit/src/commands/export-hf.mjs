import { existsSync, mkdirSync } from "node:fs";
import { err } from "../envelope.mjs";
import { KitError } from "../errors.mjs";
import { deriveAll } from "../derive.mjs";
import { gateSatisfied } from "../gates.mjs";
import { sha256File } from "../hash.mjs";
import { appendJournal } from "../journal.mjs";
import { writeAtomic } from "../fsx.mjs";
import { loadProject, resolveProject } from "../project.mjs";
import { createContext } from "../sources.mjs";
import { renderStory } from "../story/render.mjs";
import { inputsFrom, validateStory } from "../story/validate.mjs";
import { checkAssets, exportName } from "../edit/assets-check.mjs";
import { placeFile, safePath } from "../img/commit.mjs";

function storyboardDoc(sctx, synced) {
  const rows = synced.map((a) => `| ${a.id} | ${a.kind} | v${a.v} | edit/assets/${exportName(a)} | ${a.q === undefined ? "" : `${a.q} ${a.tier}`} |`);
  return ["<!-- generated by imagine-kit export-hf; edit STORY.md through patch apply, not this file -->", "",
    renderStory({ front: sctx.story.front, shots: sctx.story.shots }), "",
    "## Assets", "", "| id | kind | version | file | q |", "| --- | --- | --- | --- | --- |", ...rows, ""].join("\n");
}

export default {
  locks: true,
  options: {},
  async run(_args, ctx) {
    const { dir, rel } = resolveProject(ctx.cwd, _args.values.project);
    if (loadProject(dir).purges?.length) throw new KitError("HARD", "media was purged from this project; HyperFrames export is disabled", { rule: "HARD-PURGED" });
    const sctx = createContext(dir);
    const derived = deriveAll(sctx);
    const empty = { shots: [], assets: [] };
    const errors = [];
    if (derived.gates.G4.state !== "approved") errors.push(err("HARD-GATES-RECORDED", "HARD", "G4", `gate G4 must be approved (state: ${derived.gates.G4.state})`));
    for (const g of ["G5a", "G5b"]) if (!gateSatisfied(derived.gates, g)) errors.push(err("HARD-GATES-RECORDED", "HARD", g, `gate ${g} must be approved before export-hf (state: ${derived.gates[g].state})`));
    if (errors.length) return { project: rel, data: empty, errors };
    const hf = safePath(dir, "edit/hyperframes.json");
    if (!hf) throw new KitError("HARD", "edit/hyperframes.json resolves outside the project", { rule: "HARD-ASSETS-APPROVED", item: "edit/hyperframes.json" });
    if (!existsSync(hf)) {
      throw new KitError("BLOCKED", "edit/ is not an initialised HyperFrames project (edit/hyperframes.json is missing); run `npx hyperframes@0.8.223 init edit`", { rule: "HARD-ROOT-MOTION" });
    }
    const check = checkAssets(dir, sctx, derived);
    const story = validateStory(inputsFrom(sctx));
    const all = [...check.errors, ...story.errors];
    if (all.length) return { project: rel, data: empty, errors: all, advice: story.advice, not_run: story.not_run };

    const assetsDir = safePath(dir, "edit/assets");
    if (!assetsDir) throw new KitError("HARD", "edit/assets resolves outside the project", { rule: "HARD-ASSETS-APPROVED", item: "edit/assets" });
    for (const a of check.used) {
      const dest = safePath(dir, `edit/assets/${exportName(a)}`);
      const src = safePath(dir, a.path);
      if (!dest || !src) throw new KitError("HARD", `${a.id}.v${a.v} resolves outside the project`, { rule: "HARD-ASSETS-APPROVED", item: `${a.id}.v${a.v}` });
    }
    const sbPath = safePath(dir, "edit/STORYBOARD.md");
    if (!sbPath) throw new KitError("HARD", "edit/STORYBOARD.md resolves outside the project", { rule: "HARD-ASSETS-APPROVED", item: "edit/STORYBOARD.md" });

    mkdirSync(assetsDir, { recursive: true });
    for (const a of check.used) {
      const dest = safePath(dir, `edit/assets/${exportName(a)}`);
      const src = safePath(dir, a.path);
      if (!dest || !src) throw new KitError("HARD", `${a.id}.v${a.v} resolves outside the project`, { rule: "HARD-ASSETS-APPROVED", item: `${a.id}.v${a.v}` });
      if (!existsSync(dest) || sha256File(dest) !== a.sha256) placeFile(src, dest);
    }
    const finalSb = safePath(dir, "edit/STORYBOARD.md");
    if (!finalSb) throw new KitError("HARD", "edit/STORYBOARD.md resolves outside the project", { rule: "HARD-ASSETS-APPROVED", item: "edit/STORYBOARD.md" });
    writeAtomic(finalSb, storyboardDoc(sctx, check.used));
    const journal_id = appendJournal(dir, { command: "export-hf", summary: `${sctx.story.shots.length} shots, ${check.used.length} assets`, now: ctx.now() });
    return { project: rel, journal_id, advice: story.advice, not_run: story.not_run,
      data: { shots: sctx.story.shots.map((s) => s.id), assets: check.used.map((a) => ({ id: a.id, v: a.v, kind: a.kind, path: `edit/assets/${exportName(a)}`, sha256: a.sha256 })) } };
  },
};
