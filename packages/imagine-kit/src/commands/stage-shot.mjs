const num = (n) => String(Math.round(n * 1000) / 1000);

function shotBrief(sctx, shot, assets) {
  const g0 = sctx.project.g0;
  const k = parsedKeys(shot);
  const lines = (k.voiceover ?? []).map((v) => `- ${v.unit} at +${num(v.offset)}s: ${sctx.units.units[v.unit]?.text ?? "(unknown unit)"}`);
  const keyLines = Object.entries(shot.keys).map(([key, raw]) => `- ${key}: ${raw}`);
  return [
    `# SHOT.md - ${shot.id}: ${shot.title}`, "",
    "Generated by `stage-shot`. Build one scene for this shot only.", "",
    "## Frame", `- format: ${g0.format}, ${g0.width}x${g0.height} at ${g0.fps} fps`,
    `- duration: ${num(k.duration ?? k.duration_est ?? 0)}s (shadow time starts at 0)`, "",
    "## Narrative", shot.narrative || "(none)", "",
    "## Shot keys (storyboard, previz, fx)", ...keyLines, "",
    "## Voiceover in this shot", ...(lines.length ? lines : ["- none"]), "",
    "## Assets (copied into assets/)", ...(assets.length ? assets.map((a) => `- ${a.decl.id} (${a.entry.kind}) -> assets/${basename(a.entry.path)}`) : ["- none"]), "",
    "## Output contract",
    `- compositions/${shot.id}.html: a sub-composition wrapped in <template>, data-composition-id="${shot.id}", timeline registered as window.__timelines["${shot.id}"], tweens with fromTo() only.`,
    "- index.motion.json (optional): { \"version\": 1, \"assertions\": [...] } in shadow-local seconds; promote-shot shifts appearsBy.bySec by the shot start.",
    "- Do not edit index.html here; it is the preview host that stage-shot wrote.", "",
  ].join("\n");
}

function hostHtml(g0, id, seconds) {
  const attrs = `data-width="${g0.width}" data-height="${g0.height}" data-start="0" data-duration="${num(seconds)}"`;
  return `<!doctype html>\n<html><head><meta charset="utf-8"><script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script></head>\n<body>\n`
    + `<div id="root" data-composition-id="root" ${attrs}>\n`
    + `  <div id="host-${id}" class="scene" data-composition-id="${id}" data-composition-src="compositions/${id}.html" data-start="0" data-duration="${num(seconds)}" data-track-index="0"></div>\n`
    + `  <script>window.__timelines = window.__timelines || {}; window.__timelines["root"] = gsap.timeline({ paused: true });</script>\n</div>\n</body></html>\n`;
}

export default {
  locks: false,
  options: {},
  async run({ values, positionals }, ctx) {
    if (positionals.length !== 1) throw new UsageError("usage: stage-shot <shot id>");
    const { dir, rel } = resolveProject(ctx.cwd, values.project);
    return stage(ctx, dir, rel, positionals[0]);
  },
};

async function stage(ctx, dir, rel, id) {
  const sctx = createContext(dir);
  const shot = shotOrThrow(sctx, id);
  const derived = deriveAll(sctx);
  const shadowRel = `stage/edit/${id}`;
  const out = (errors) => ({ project: rel, data: { shot: id, path: shadowRel }, errors });

  const pre = editPreconditions(dir, derived, shot);
  if (pre.errors.length) return out(pre.errors);
  const assets = shotAssets(sctx, shot, dir);
  if (assets.errors.length) return out(assets.errors);

  const shadow = safePath(dir, shadowRel);
  if (!shadow) return out([err("HARD-SCENE-LINT", "HARD", id, `${shadowRel} is outside the project`)]);

  const compDir = safePath(dir, `stage/edit/${id}/compositions`);
  const assetsDir = safePath(dir, `stage/edit/${id}/assets`);
  const shadowHf = safePath(dir, `stage/edit/${id}/hyperframes.json`);
  const briefPath = safePath(dir, `stage/edit/${id}/SHOT.md`);
  const indexPath = safePath(dir, `stage/edit/${id}/index.html`);
  const srcHf = safePath(dir, "edit/hyperframes.json");
  if (!compDir || !assetsDir || !shadowHf || !briefPath || !indexPath || !srcHf) {
    return out([err("HARD-SCENE-LINT", "HARD", id, `${shadowRel} destination is outside the project`)]);
  }

  for (const a of assets.found) {
    const syncedRel = `edit/assets/${basename(a.entry.path)}`;
    const synced = safePath(dir, syncedRel);
    const src = synced && existsSync(synced) ? synced : safePath(dir, a.entry.path);
    const dest = safePath(dir, `stage/edit/${id}/assets/${basename(a.entry.path)}`);
    if (!src || !dest) return out([err("HARD-ASSETS-APPROVED", "HARD", a.decl.id, `asset ${a.decl.id} path leaves project`)]);
  }

  const k = parsedKeys(shot);
  return withLock(dir, async () => {
    const lockShadow = safePath(dir, shadowRel);
    if (!lockShadow) return out([err("HARD-SCENE-LINT", "HARD", id, `${shadowRel} is outside the project`)]);
    const lockCompDir = safePath(dir, `stage/edit/${id}/compositions`);
    const lockAssetsDir = safePath(dir, `stage/edit/${id}/assets`);
    const lockShadowHf = safePath(dir, `stage/edit/${id}/hyperframes.json`);
    const lockBriefPath = safePath(dir, `stage/edit/${id}/SHOT.md`);
    const lockIndexPath = safePath(dir, `stage/edit/${id}/index.html`);
    const lockSrcHf = safePath(dir, "edit/hyperframes.json");
    if (!lockCompDir || !lockAssetsDir || !lockShadowHf || !lockBriefPath || !lockIndexPath || !lockSrcHf) {
      return out([err("HARD-SCENE-LINT", "HARD", id, `${shadowRel} destination is outside the project`)]);
    }

    mkdirSync(lockCompDir, { recursive: true });
    mkdirSync(lockAssetsDir, { recursive: true });
    copyFileSync(lockSrcHf, lockShadowHf);
    for (const a of assets.found) {
      const syncedRel = `edit/assets/${basename(a.entry.path)}`;
      const synced = safePath(dir, syncedRel);
      const src = synced && existsSync(synced) ? synced : safePath(dir, a.entry.path);
      const dest = safePath(dir, `stage/edit/${id}/assets/${basename(a.entry.path)}`);
      if (!src || !dest) return out([err("HARD-ASSETS-APPROVED", "HARD", a.decl.id, `asset ${a.decl.id} path leaves project`)]);
      copyFileSync(src, dest);
    }
    // SHOT.md and the preview host are regenerated; the scene-builder's own composition and motion file are never touched.
    writeAtomic(lockBriefPath, shotBrief(sctx, shot, assets.found));
    writeAtomic(lockIndexPath, hostHtml(sctx.project.g0, id, k.duration ?? k.duration_est ?? 1));
    const journal_id = appendJournal(dir, { command: "stage-shot", summary: `${id} -> stage/edit/${id}`, now: ctx.now() });
    return { project: rel, journal_id, data: { shot: id, path: shadowRel } };
  });
}
