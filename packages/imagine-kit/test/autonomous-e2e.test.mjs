import test from "node:test";
import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { CHECKPOINTS, checkpointItemId } from "../src/checkpoints.mjs";
import { updateDelivery, publishPlatform, DELIVERY_ITEM_ID } from "../src/delivery.mjs";
import { writeEvidence } from "../src/evidence.mjs";
import { recordConsent } from "../src/consent.mjs";
import { sha256File } from "../src/hash.mjs";
import { BIBLE, cli, getProject, makeProject, put, seedCanon, seedMinimalStory } from "./helpers/fixture.mjs";
// Requirements 2.2-2.5: Creative_Brief -> Production_Complete with zero user approval prompts.
//
// What is real: `new` (the Creative_Brief), the Q1 Checkpoint run through the `checkpoint` command (real story validators),
// Evidence_Records, derived state, updateDelivery and publishPlatform.
// What is stubbed: the creative stages (canon files and STORY.md are written from fixtures, not generated by an agent),
// and Q2/Q3. Those Checks need image/audio/video tooling and evaluators, so a fixture evaluator
// ("fixture-evaluator", full capabilities) writes one passed Evidence_Record per Check through writeEvidence.
// Approval prompts are modelled by `askUser`, the only way a script could reach the user. The run must never call it.
const NOW = new Date("2026-11-01T10:00:00Z");
function prompts() {
  const asked = [];
  return { asked, askUser: (why) => { asked.push(why); throw new Error(`unexpected user prompt: ${why}`); } };
}
const RENDER = "a".repeat(64);
function fixtureEvidence(dir, checkpointId, scope, result = "passed") {
  const cp = CHECKPOINTS[checkpointId];
  for (const c of cp.checks) {
    const w = writeEvidence(dir, { itemId: checkpointItemId(checkpointId, scope), checkId: c.id, evaluator: "fixture-evaluator",
      evaluatorCapabilities: ["text", "file-hash", "image-inspection", "audio-analysis", "video-probe"], requires: c.requires,
      ruleVersion: c.ruleVersion, inputHashes: { "render:mp4": RENDER }, outputRefs: [], result, now: NOW });
    assert.deepEqual(w.errors, []);
  }
}
test("a valid brief reaches Production_Complete with zero approval prompts and never publishes", async () => {
  const { askUser, asked } = prompts();
  // Creative_Brief: complete and unambiguous fields, no approval step.
  const { cwd, dir } = await makeProject();
  seedCanon(dir);
  // The narrator needs a voice for the voice-usage-permission Check.
  put(dir, "bible.yaml", "narrator:\n  voice:\n    engine: pocket-tts\n    source: builtin:eve\n" + BIBLE);
  await seedMinimalStory(dir);
  // Q1 runs for real through the command. Checks that need an evaluator are not_run; Q1 reports a state, never asks.
  const q1 = await cli(cwd, "checkpoint", "Q1", "run");
  assert.equal(q1.exit, 0, JSON.stringify(q1.env.errors));
  assert.notEqual(q1.env.data.state, "failed", JSON.stringify(q1.env.data.checks));
  fixtureEvidence(dir, "Q1", []);   // stub: any Q1 Check left unevaluated by the real run
  fixtureEvidence(dir, "Q2", []);   // stub
  fixtureEvidence(dir, "Q3", []);   // stub
  const status = await cli(cwd, "status");
  for (const q of ["Q1", "Q2", "Q3"]) assert.equal(status.env.data.checkpoints[q].state, "passed", q);
  // Production_Complete
  const delivered = updateDelivery(dir, { render: RENDER, now: NOW });
  assert.equal(delivered.state, "ready");
  assert.deepEqual(delivered.pending, []);
  const project = getProject(dir);
  assert.equal(project.items[DELIVERY_ITEM_ID].state, "ready");
  // Zero prompts: nothing asked, no consent and no gate decision was needed.
  assert.deepEqual(asked, []);
  assert.deepEqual(project.consents ?? [], []);
  assert.deepEqual(Object.values(project.items).filter((i) => i.decision), []);
  // Reaching Production_Complete did not publish. Publishing is the one step that needs the user.
  const file = join(dir, "final.mp4");
  writeFileSync(file, "film bytes");
  const refused = publishPlatform(dir, { platform: "youtube", file: "final.mp4", now: NOW });
  assert.equal(refused.published, false);
  assert.equal(refused.errors[0].rule, "CONSENT-REQUIRED");
  assert.equal(getProject(dir).items[DELIVERY_ITEM_ID].state, "ready");
  void askUser;
});
test("publication after Production_Complete needs a Publication_Authorization for the exact file", async () => {
  const { dir } = await makeProject();
  seedCanon(dir);
  await seedMinimalStory(dir);
  for (const q of ["Q1", "Q2", "Q3"]) fixtureEvidence(dir, q, []);
  assert.equal(updateDelivery(dir, { render: RENDER, now: NOW }).state, "ready");
  const file = join(dir, "final.mp4");
  writeFileSync(file, "film bytes");
  const c = recordConsent(dir, { kind: "publication", scope: "youtube", quote: "yes, publish the film to youtube", fileHash: sha256File(file), now: NOW });
  assert.deepEqual(c.errors ?? [], []);
  assert.equal(publishPlatform(dir, { platform: "youtube", file: "final.mp4", now: NOW }).published, true);
  assert.equal(getProject(dir).items[DELIVERY_ITEM_ID].state, "published");
});
test("a failing Q3 keeps the film out of Production_Complete (defective end-to-end run)", async () => {
  const { dir } = await makeProject();
  seedCanon(dir);
  await seedMinimalStory(dir);
  for (const q of ["Q1", "Q2"]) fixtureEvidence(dir, q, []);
  fixtureEvidence(dir, "Q3", [], "failed");
  const r = updateDelivery(dir, { render: RENDER, now: NOW });
  assert.equal(r.state, "pending");
  assert.ok(r.pending.length > 0);
});
