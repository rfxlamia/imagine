test("export-hf syncs approved assets into edit/assets and writes STORYBOARD.md; data is {shots, assets}", async () => {
  const p = await editProject();
  await addAudio(p);
  unlinkSync(join(p.dir, "edit/STORYBOARD.md"));
  const r = await p.run({}, "export-hf");
  assert.equal(r.exit, 0, JSON.stringify(r.env.errors));
  assert.deepEqual(r.env.data.shots, ["s01", "s02"]);
  assert.deepEqual(r.env.data.assets.map((a) => a.path).sort(), ["edit/assets/L01.v1.wav", "edit/assets/L02.v1.wav", "edit/assets/L03.v1.wav", "edit/assets/bed.v1.wav", "edit/assets/bg.v1.png"]);
  for (const a of r.env.data.assets) assert.equal(sha256File(join(p.dir, a.path)), a.sha256);
  const doc = readFileSync(join(p.dir, "edit/STORYBOARD.md"), "utf8");
  assert.match(doc, /^<!-- generated by imagine-kit export-hf/);
  assert.match(doc, /## Scene s01/);
  assert.match(doc, /\| bg \| img \| v1 \| edit\/assets\/bg\.v1\.png \|/);
  assert.equal(existsSync(join(p.dir, "edit/index.motion.json")), false, "export-hf never touches the motion file");
  const again = await p.run({}, "export-hf");
  assert.equal(again.exit, 0);
});

