test("HARD-ASSETS-APPROVED: symlinking edit/ outside the project fails before creating or modifying any outside file", async () => {
  // Case 1: project with approved assets
  const p = await editProject();
  await addAudio(p);
  const outside1 = mkdtempSync(join(tmpdir(), "imagine-outside-edit-"));
  writeFileSync(join(outside1, "hyperframes.json"), "{}\n");
  rmSync(join(p.dir, "edit"), { recursive: true, force: true });
  symlinkSync(outside1, join(p.dir, "edit"));

  const r1 = await p.run({}, "export-hf");
  assert.equal(r1.exit, 1);
  assert.ok(r1.env.errors.some((e) => e.rule === "HARD-ASSETS-APPROVED" && /outside the project/.test(e.message)));
  assert.equal(existsSync(join(outside1, "assets")), false, "outside assets directory must not be created");
  assert.equal(existsSync(join(outside1, "STORYBOARD.md")), false, "outside STORYBOARD.md must not be created");

  // Case 2: project with no exported assets
  const noAssetShots = [
    shot("s01", { scene: "stairs", duration_est: "6s", duration: "6s", voiceover: "[T01, T02@2.5]", framing: "wide" }, "Stairs", "She climbs."),
    shot("s02", { scene: "lamp", duration_est: "7s", duration: "7s", voiceover: "[T03]" }, "Lamp", "She lights it.")
  ];
  const q = await editProject({ mode: "text-led", shots: noAssetShots });
  setManifest(q.dir, (m) => { m.assets = []; });
  const outside2 = mkdtempSync(join(tmpdir(), "imagine-outside-edit-noassets-"));
  writeFileSync(join(outside2, "hyperframes.json"), "{}\n");
  rmSync(join(q.dir, "edit"), { recursive: true, force: true });
  symlinkSync(outside2, join(q.dir, "edit"));

  const r2 = await q.run({}, "export-hf");
  assert.equal(r2.exit, 1);
  assert.ok(r2.env.errors.some((e) => e.rule === "HARD-ASSETS-APPROVED" && /outside the project/.test(e.message)));
  assert.equal(existsSync(join(outside2, "assets")), false, "outside assets directory must not be created in no-asset project");
  assert.equal(existsSync(join(outside2, "STORYBOARD.md")), false, "outside STORYBOARD.md must not be created in no-asset project");
});

